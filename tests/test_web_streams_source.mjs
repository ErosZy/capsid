import assert from 'node:assert/strict';
import {test} from 'node:test';
import fs from 'node:fs';
import {createHash} from 'node:crypto';
import vm from 'node:vm';

const root=new URL('../',import.meta.url),read=path=>fs.readFileSync(new URL(path,root));
const provenance=JSON.parse(read('tools/web-streams-compat-upstream.json'));
const bundle=read('js/streams.js').toString();
const hash=value=>createHash('sha256').update(value).digest('hex');
// These VM controls exercise BYOB behavior. Actual native buffer aliasing is
// verified by the C++ regression and by real worker/reference observations.
const unavailableBufferAlias=()=>{throw new Error('BYOB control requested a native buffer alias');};

test('stream bundle retains the pinned source, controlled patch and complete license',()=>{
    assert.equal(provenance.commit,'12b4fedec6c01503a137d837204ca0b85992461e');
    assert.equal(provenance.tag,'v4.3.0');assert.equal(provenance.esbuild,'0.28.1');
    assert.equal(Object.keys(provenance.files).length,61);
    assert.equal(hash(read(provenance.patch.path)),provenance.patch.sha256);
    const license=read(provenance.license.path);assert.equal(hash(license),provenance.license.sha256);
    assert.ok(bundle.startsWith('/*\nGenerated by tools/generate-web-streams-compat.py;'));
    assert.ok(bundle.includes(provenance.commit));assert.ok(bundle.includes(provenance.patch.sha256));
    assert.ok(bundle.includes(license.toString().trimEnd()));
});

async function realm(){
    const context=vm.createContext({});
    const module=new vm.SourceTextModule(bundle,{context});
    await module.link(()=>{throw Error('stream bundle must be self-contained');});
    // Node installs its own per-context module symbol while linking. Measure
    // the public surface immediately before evaluating the product module.
    const before=vm.runInContext('Reflect.ownKeys(globalThis)',context);
    await module.evaluate();
    return {context,module,before};
}
test('compatibility controls stay private and install only the thirteen stream globals',async()=>{
    const {context,module,before}=await realm();
    assert.deepEqual(Object.keys(module.namespace),['configureByteStreamCompatibility','markNativeByteStream']);
    const added=vm.runInContext('Reflect.ownKeys(globalThis)',context).filter(key=>!before.includes(key));
    assert.deepEqual(Array.from(added).sort(),['ByteLengthQueuingStrategy','CountQueuingStrategy',
        'ReadableByteStreamController','ReadableStream','ReadableStreamBYOBReader','ReadableStreamBYOBRequest',
        'ReadableStreamDefaultController','ReadableStreamDefaultReader','TransformStream',
        'TransformStreamDefaultController','WritableStream','WritableStreamDefaultController','WritableStreamDefaultWriter'].sort());
});
for(const profile of ['unconfigured','standard','native'])test('private controller profile '+profile,async()=>{
    const {context,module}=await realm();
    if(profile!=='unconfigured')module.namespace.configureByteStreamCompatibility(
        vm.runInContext('detail=>new Error(detail)',context), unavailableBufferAlias);
    context.mark=profile==='native'?module.namespace.markNativeByteStream:stream=>stream;
    const observed=JSON.parse(await vm.runInContext(`(async()=>{
        const stream=mark(new ReadableStream({type:'bytes',start(controller){
            controller.enqueue(new Uint8Array([102,105,114,115,116]));controller.close();
        }}));
        const reader=stream.getReader({mode:'byob'});reader.closed.catch(()=>{});
        const buffer=new ArrayBuffer(32);new Uint8Array(buffer).fill(165);
        try{const read=await reader.read(new Float64Array(buffer,8,2));
            return JSON.stringify({done:read.done,type:read.value.constructor.name,offset:read.value.byteOffset,
                length:read.value.byteLength,backing:Array.from(new Uint8Array(read.value.buffer))});
        }catch(error){return JSON.stringify({name:error.name,message:error.message});}
    })()`,context));
    if(profile==='standard')assert.deepEqual(observed,{done:false,type:'Float64Array',offset:8,length:0,
        backing:[...Array(8).fill(165),102,105,114,115,116,...Array(19).fill(165)]});
    else assert.deepEqual(observed,{name:'TypeError',message:'Insufficient bytes to fill elements in the given buffer'});
});
for(const length of [0,5,8,9])test('standard pending EOF preserves '+length+' supplied bytes',async()=>{
    const {context,module}=await realm();
    module.namespace.configureByteStreamCompatibility(vm.runInContext('detail=>new Error(detail)',context), unavailableBufferAlias);
    context.payloadLength=length;
    const observed=JSON.parse(await vm.runInContext(`(async()=>{
        let controller;const trace=[];
        const stream=new ReadableStream({type:'bytes',start(value){controller=value;}});
        const reader=stream.getReader({mode:'byob'});
        const closed=reader.closed.then(()=>trace.push('closed'));
        const buffer=new ArrayBuffer(32);new Uint8Array(buffer).fill(165);
        const pending=reader.read(new Float64Array(buffer,8,2),{min:2.9}).then(read=>{
            trace.push('read');return {done:read.done,offset:read.value.byteOffset,length:read.value.byteLength,
                type:read.value.constructor.name,backing:Array.from(new Uint8Array(read.value.buffer))};
        });
        if(payloadLength)controller.enqueue(Uint8Array.from({length:payloadLength},(_,i)=>i+1));
        controller.close();const read=await pending;await closed;reader.releaseLock();
        return JSON.stringify({read,trace,locked:stream.locked,detached:buffer.byteLength===0});
    })()`,context));
    assert.deepEqual(observed,{read:{done:length===0,offset:8,length:length<8?0:8,type:'Float64Array',
        backing:[...Array(8).fill(165),...Array.from({length},(_,i)=>i+1),...Array(24-length).fill(165)]},
        trace:['read','closed'],locked:false,detached:true});
});
test('native controller keeps the explicit close then respond-zero protocol',async()=>{
    const {context,module}=await realm();
    module.namespace.configureByteStreamCompatibility(vm.runInContext('detail=>new Error(detail)',context), unavailableBufferAlias);
    context.markNative=module.namespace.markNativeByteStream;
    const observed=JSON.parse(await vm.runInContext(`(async()=>{
        let controller,settled=false;
        const stream=markNative(new ReadableStream({type:'bytes',start(value){controller=value;}}));
        const reader=stream.getReader({mode:'byob'});
        const read=reader.read(new Uint8Array(4)).then(value=>{settled=true;return value;});
        const request=controller.byobRequest;controller.close();await Promise.resolve();
        const beforeRespond=settled;request.respond(0);const value=await read;reader.releaseLock();
        return JSON.stringify({beforeRespond,done:value.done,length:value.value.byteLength,locked:stream.locked});
    })()`,context));
    assert.deepEqual(observed,{beforeRespond:false,done:true,length:0,locked:false});
});

for(const profile of ['unconfigured','standard','native'])
for(const shape of ['closed','queued','pulled'])
for(const mode of ['default','byob'])
for(const branch of [0,1])test(`byte tee EOF ${profile}/${shape}/${mode}/${branch}`,{timeout:500},async()=>{
    const {context,module}=await realm();
    // Aliasing does not affect the ownership/state observations in this VM.
    // Actual native EOF buffer identity is covered by the worker regressions.
    if(profile!=='unconfigured')module.namespace.configureByteStreamCompatibility(
        vm.runInContext('detail=>new Error(detail)',context),buffer=>buffer);
    Object.assign(context,{shape,mode,branch,mark:profile==='native'?module.namespace.markNativeByteStream:stream=>stream});
    const observed=JSON.parse(await vm.runInContext(`(async()=>{
        let sent=false;
        const close=controller=>{controller.close();controller.byobRequest?.respond(0);};
        const source=mark(new ReadableStream({type:'bytes',start(controller){
            if(shape==='closed')close(controller);
            if(shape==='queued'){controller.enqueue(new Uint8Array([1,2,3]));close(controller);}
        },pull(controller){
            if(sent)close(controller);
            else{sent=true;controller.enqueue(new Uint8Array([1,2,3]));}
        }}));
        const branches=source.tee();
        async function drain(stream){
            const reader=stream.getReader(mode==='byob'?{mode:'byob'}:undefined),bytes=[];
            let eof;
            try{
                for(;;){
                    const value=await(mode==='byob'?reader.read(new Uint8Array(8)):reader.read());
                    if(value.done){eof=value.value?.byteLength??null;break;}
                    bytes.push(...value.value);
                }
                await reader.closed;
                const repeated=await(mode==='byob'?reader.read(new Uint8Array(8)):reader.read());
                if(!repeated.done)throw Error('EOF read reopened the branch');
            }finally{reader.releaseLock();}
            return {bytes,locked:stream.locked,eof};
        }
        const first=await drain(branches[branch]),second=await drain(branches[1-branch]);
        return JSON.stringify({first,second});
    })()`,context));
    for(const result of [observed.first,observed.second]){
        assert.deepEqual(result.bytes,shape==='closed'?[]:[1,2,3]);assert.equal(result.locked,false);
        assert.ok(result.eof===null||result.eof===0);
    }
});
