#!/usr/bin/env python3
"""Rebuild the checked-in stream polyfill from a verified, local upstream tree.

Normal Capsid builds use js/streams.js and do not need TypeScript or a download.
Obtain the exact upstream revision recorded in web-streams-compat-upstream.json,
then pass that checkout (or its recorded source snapshot) with --source.
"""

import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import tempfile


ROOT = Path(__file__).resolve().parent.parent
PROVENANCE = ROOT / "tools/web-streams-compat-upstream.json"


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def checked_path(base, relative):
    path = (base / relative).resolve()
    if not path.is_relative_to(base) or path == base:
        raise ValueError(f"Path escapes its input directory: {relative}")
    return path


def verify_source(source, provenance):
    # Permit a complete checkout as well as the small recorded source snapshot.
    actual = {p.relative_to(source).as_posix() for p in (source / "src").rglob("*") if p.is_file()}
    expected = {p for p in provenance["files"] if p.startswith("src/")}
    if actual != expected:
        raise ValueError("Upstream src inventory differs from the pinned source")
    for relative, record in provenance["files"].items():
        path = checked_path(source, relative)
        if path.is_symlink() or path.stat().st_size != record["bytes"] or digest(path) != record["sha256"]:
            raise ValueError(f"Upstream input differs from the pinned source: {relative}")


def generate(args):
    provenance = json.loads(PROVENANCE.read_text(encoding="utf-8"))
    source = args.source.resolve(strict=True)
    verify_source(source, provenance)
    patch = checked_path(ROOT, provenance["patch"]["path"])
    license_file = checked_path(ROOT, provenance["license"]["path"])
    for path, record in ((patch, provenance["patch"]), (license_file, provenance["license"])):
        if digest(path) != record["sha256"]:
            raise ValueError(f"Controlled input differs from its provenance: {path.name}")
    version = subprocess.check_output([str(args.esbuild.resolve(strict=True)), "--version"], text=True).strip()
    if version != provenance["esbuild"]:
        raise ValueError(f"Expected esbuild {provenance['esbuild']}, got {version}")

    work_root = args.work_dir.resolve()
    work_root.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(prefix="web-streams-", dir=work_root)).resolve()
    if staging.parent != work_root:
        raise ValueError("Staging directory escapes the work directory")
    try:
        for relative in provenance["files"]:
            target = checked_path(staging, relative)
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(source / relative, target)
        subprocess.run(["git", "init", "--quiet", str(staging)], check=True)
        subprocess.run(["git", "-c", "core.autocrlf=false", "apply", "--check", str(patch)], cwd=staging, check=True)
        subprocess.run(["git", "-c", "core.autocrlf=false", "apply", str(patch)], cwd=staging, check=True)
        license_text = license_file.read_text(encoding="utf-8").rstrip()
        banner = ("/*\nGenerated by tools/generate-web-streams-compat.py; do not edit directly.\n"
                  f"web-streams-polyfill {provenance['tag']} ({provenance['commit']})\n"
                  f"Capsid patch SHA-256: {provenance['patch']['sha256']}\n\n{license_text}\n*/")
        output = staging / "streams.js"
        metadata = staging / "bundle-inputs.json"
        subprocess.run([str(args.esbuild.resolve()), "src/capsid-polyfill.ts", "--bundle", "--format=esm",
                        "--platform=neutral", "--target=esnext", "--define:DEBUG=false", "--keep-names",
                        "--minify-syntax", f"--banner:js={banner}", "--outfile=streams.js",
                        "--metafile=bundle-inputs.json"], cwd=staging, check=True)
        bundle = json.loads(metadata.read_text(encoding="utf-8"))
        if any(out["imports"] for out in bundle["outputs"].values()):
            raise ValueError("The generated stream bundle has external imports")
        contents = output.read_bytes()
        if args.check:
            if contents != args.output.read_bytes():
                raise ValueError("Checked-in stream bundle differs from the regenerated source")
        else:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_bytes(contents)
        print(json.dumps({"complete": True, "check": args.check, "sourceFiles": len(provenance["files"]),
                          "sha256": hashlib.sha256(contents).hexdigest(), "bytes": len(contents)}))
    finally:
        # Verify the resolved deletion target remains in this invocation's work directory.
        if staging.resolve().parent != work_root or not staging.name.startswith("web-streams-"):
            raise ValueError("Refusing to remove an unexpected staging directory")
        shutil.rmtree(staging)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", required=True, type=Path)
    parser.add_argument("--esbuild", required=True, type=Path)
    parser.add_argument("--work-dir", required=True, type=Path)
    parser.add_argument("--output", type=Path, default=ROOT / "js/streams.js")
    parser.add_argument("--check", action="store_true")
    generate(parser.parse_args())


if __name__ == "__main__":
    main()
